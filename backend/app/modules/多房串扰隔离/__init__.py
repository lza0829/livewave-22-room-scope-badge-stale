"""多房串扰隔离（已实现）。

与「房间级水位线」共用同一全局口径：**甲——每房独立水位**。

绑定自洽三要素（任一断裂即为半截串房缺陷）：
1. 水位行：主键=房间键，推进语句 WHERE 必带本房键（见 modules.房间级水位线.推进）；
2. 关窗扫描：只查 `热度窗 WHERE 房间键=本房键 AND 状态='开启'`，扫描范围=本房；
3. 事件归属：事件只允许落入本房窗键（窗键前缀=房间键），旁路事件不挂窗键。

对照口径乙（全局统一水位）在本系统**不成立**：禁止宣称全局水位却只关本房，也禁止
拿他房水位关本房窗。甲/乙可区分判据——A/B 两房均有开启且窗止可被越过的窗，只推 A：
甲仅关 A、B 仍开；乙则 A、B 到期窗皆关。
"""
from __future__ import annotations

状态 = "已实现"
采用口径 = "甲：每房独立水位"


def 同房校验(事件房间键: str, 水位房间键: str, 窗房间键: str | None = None) -> None:
    """断言房键绑定一致；不一致直接抛错，宁可拒绝入流也不写半截串房数据。"""
    if 事件房间键 != 水位房间键:
        raise RuntimeError(
            f"串房拒绝：事件房[{事件房间键}] 与水位行房[{水位房间键}] 不一致"
        )
    if 窗房间键 is not None and 事件房间键 != 窗房间键:
        raise RuntimeError(
            f"串房拒绝：事件房[{事件房间键}] 与热度窗房[{窗房间键}] 不一致"
        )


def 关窗房键集合() -> set[str]:
    """甲口径下关窗扫描的房键集合 = {事件本房}；乙口径才会是全部房。"""
    return {"本房"}
