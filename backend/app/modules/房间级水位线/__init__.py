"""房间级水位线（已实现）。

全局唯一隔离口径（架构取舍，二选一，本系统选定**甲：每房独立水位**）：

- 甲（本系统采用）：水位表主键 = 房间键。一房事件只抬本房水位，关窗扫描只扫本房
  开启窗；他房水位行、他房窗一律不受影响。
- 乙（未采用，仅作对照）：全局统一水位，任一房事件抬全局水位，关窗扫描对所有房执行，
  水位越过窗止的他房窗也关闭。

两口径对「A/B 两房均有开启窗、只推 A 房事件」的可区分结论：
- 甲：仅 A 房到期窗关闭，B 房窗仍开启；
- 乙：A、B 凡水位越过窗止的窗全部关闭。

本模块是水位行的**唯一写入口**与房级只读口径出口：所有推进都按房间键条件更新，
房键与水位行、关窗扫描三者绑定自洽，并发下不允许出现「A 房水位写到 B 房」的半截串房。
"""
from __future__ import annotations

from app.services import 时间

状态 = "已实现"


隔离口径 = "每房独立水位"
水位粒度 = "房间"          
水位主键 = "房间键"
扫描范围 = "本房开启窗"     
跨房关窗 = False            


def 口径() -> dict:
    """只读：返回当前全局贯彻的隔离口径，供接口/测试区分甲乙。"""
    return {
        "隔离口径": 隔离口径,
        "水位粒度": 水位粒度,
        "水位主键": 水位主键,
        "扫描范围": 扫描范围,
        "跨房关窗": 跨房关窗,
        "只推A房时B房窗": "保持开启（甲口径）",
    }


def 确保房水位行(conn, 房间键: str, 开播事件时: str, 允许迟到秒: int, 处理时: str) -> None:
    """幂等插入本房水位行；已存在则不动。INSERT 自带房间键，不触碰他房行。"""
    conn.execute(
        """INSERT OR IGNORE INTO 水位线(房间键, 事件时水位, 允许迟到秒, 更新处理时)
           VALUES (?,?,?,?)""",
        (房间键, 开播事件时, 允许迟到秒, 处理时),
    )


def 推进(conn, 房间键: str, 候选事件时: str, 处理时: str) -> dict:
    """按房间键条件推进本房水位（水位只升不退）。

    返回 {"推进": bool, "房间键": str, "事件时水位": str}。
    UPDATE 的 WHERE 同时绑定房间键与旧水位：并发下另一房的写入无法满足本房键条件，
    从语句层面杜绝「A 房事件写到 B 房水位行」。
    """
    行 = conn.execute(
        "SELECT 事件时水位 FROM 水位线 WHERE 房间键=?", (房间键,)
    ).fetchone()
    if 行 is None:
        raise RuntimeError(f"房级水位行缺失，拒绝无主键推进：{房间键}")
    旧水位 = 行["事件时水位"]
    if 时间.解析(候选事件时) <= 时间.解析(旧水位):
        return {"推进": False, "房间键": 房间键, "事件时水位": 旧水位}
    cur = conn.execute(
        "UPDATE 水位线 SET 事件时水位=?, 更新处理时=? WHERE 房间键=? AND 事件时水位=?",
        (候选事件时, 处理时, 房间键, 旧水位),
    )
    if cur.rowcount != 1:
        
        新行 = conn.execute(
            "SELECT 事件时水位 FROM 水位线 WHERE 房间键=?", (房间键,)
        ).fetchone()
        return {"推进": False, "房间键": 房间键, "事件时水位": 新行["事件时水位"]}
    return {"推进": True, "房间键": 房间键, "事件时水位": 候选事件时}


def 只读(conn, 房间键: str | None = None) -> list[dict]:
    """房级水位只读接口：每房给出 水位口径/扫描范围/valid。

    valid 三条件：①水位行存在且所属直播间存在；②事件时水位可解析；
    ③水位不早于本房开播事件时（水位只升不退的自洽检查）。
    """
    房行 = conn.execute("SELECT * FROM 直播间 ORDER BY 房间键").fetchall()
    out: list[dict] = []
    for 房 in 房行:
        if 房间键 is not None and 房["房间键"] != 房间键:
            continue
        wm = conn.execute(
            "SELECT * FROM 水位线 WHERE 房间键=?", (房["房间键"],)
        ).fetchone()
        项 = {
            "房间键": 房["房间键"],
            "水位粒度": 水位粒度,
            "水位主键": 水位主键,
            "扫描范围": 扫描范围,
            "跨房关窗": 跨房关窗,
            "隔离口径": 隔离口径,
        }
        if wm is None:
            项.update({"valid": False, "无效原因": "缺水位行",
                       "事件时水位": None, "允许迟到秒": None, "更新处理时": None})
            out.append(项)
            continue
        try:
            水位时 = 时间.解析(wm["事件时水位"])
            可解析 = True
        except (ValueError, TypeError):
            水位时 = None
            可解析 = False
        不回退 = 可解析 and 水位时 >= 时间.解析(房["开播事件时"])
        项.update(
            {
                "事件时水位": wm["事件时水位"],
                "允许迟到秒": int(wm["允许迟到秒"]),
                "更新处理时": wm["更新处理时"],
                "开播事件时": 房["开播事件时"],
                "valid": bool(可解析 and 不回退),
                **({} if 可解析 and 不回退 else
                   {"无效原因": "水位时间不可解析" if not 可解析 else "水位早于开播（回退）"}),
            }
        )
        out.append(项)
    return out
