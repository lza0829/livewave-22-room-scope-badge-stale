"""扫描范围徽标（已实现）。

全局唯一设计取舍——**「事件房键钉本房徽标」**（与 modules.房间级水位线 的甲口径同源，
全局只贯彻这一种；对照口径「全局切换工单扩权」**未采用**，工单仅登记审计、永不扩权）：

- 每次房级抬升成功，必须在**同一事务、同一票**把本房徽标刷新为本房范围，四要素齐备：
  范围=本房、房键=本房键、水位值=本房水位行的当前值、徽标世代单调递增；
- 即使历史上存在陈旧的全局/他房徽标，也必须在本次抬升中刷回本房，禁止保留或写回全局；
- 关窗扫描只能扫徽标声明的范围；徽标缺失/范围非本房/房键与水位行分叉时直接拒绝扫描
  （fail-closed），宁可整票回滚也不带病关窗；
- 徽标刷新失败时调用方不得吞异常：本房水位已写也必须整票回滚，杜绝「水位已抬、徽标陈旧」。

表 `扫描范围徽标` 为追加式历史（每房一行最新世代 + 全世代可审计）；表 `全局切换工单`
只登记工单，任何工单都不构成把徽标改成全局的授权。

本模块是徽标的唯一写入口与核证只读口径出口；只读函数绝不写库。
"""
from __future__ import annotations

from app.seed import 此刻
from app.services import 时间

状态 = "已实现"

本房范围 = "本房"
全局范围 = "全局"
采用取舍 = "事件房键钉本房徽标"
工单扩权 = False  # 对照口径「全局切换工单扩权」未采用


def 取最新徽标(conn, 房间键: str) -> dict | None:
    row = conn.execute(
        "SELECT * FROM 扫描范围徽标 WHERE 房间键=? ORDER BY 徽标世代 DESC, 编号 DESC LIMIT 1",
        (房间键,),
    ).fetchone()
    return dict(row) if row else None


def 确保房徽标行(conn, 房间键: str, 水位值: str) -> dict:
    """幂等确保本房存在世代 0 的本房徽标（与水位行引导同事务）。

    仅在该房尚无任何徽标行时插入；已存在（含历史全局/陈旧行）则原样返回，
    陈旧行留给下一次 同票刷徽标 按抬升刷回本房。
    """
    最新 = 取最新徽标(conn, 房间键)
    if 最新 is not None:
        return 最新
    conn.execute(
        """INSERT INTO 扫描范围徽标(房间键, 范围, 水位值, 徽标世代, 时刻)
           VALUES (?,?,?,?,?)""",
        (房间键, 本房范围, 水位值, 0, 此刻()),
    )
    行 = 取最新徽标(conn, 房间键)
    if 行 is None or 行["范围"] != 本房范围 or 行["房间键"] != 房间键:
        raise RuntimeError(f"徽标引导自核失败，拒绝半截态：{房间键}")
    return 行


def 同票刷徽标(conn, 房间键: str, 水位值: str) -> dict:
    """房级抬升成功后的同票徽标刷新（唯一写入口）。

    硬规则：
    - 房键不允许为空（禁止写无房键的全局徽标）；
    - 新徽标恒为「本房」范围——即使上一世代是陈旧全局也必须刷回本房；
    - 水位值必须与本房水位行当前值一致，房键必须与水位行主键一致，否则抛错整票回滚；
    - 世代按房单调递增；同房同水位重复调用幂等（不新增世代）。

    返回最新徽标行。任何异常都向上抛，由装载事务整票回滚。
    """
    if not 房间键:
        raise RuntimeError("徽标刷新拒绝：房键为空，禁止写全局徽标")

    水位行 = conn.execute(
        "SELECT 房间键, 事件时水位 FROM 水位线 WHERE 房间键=?", (房间键,)
    ).fetchone()
    if 水位行 is None:
        raise RuntimeError(f"徽标刷新拒绝：本房水位行缺失：{房间键}")
    if 水位行["房间键"] != 房间键 or 水位行["事件时水位"] != 水位值:
        raise RuntimeError(
            f"徽标刷新拒绝：徽标房键/水位值与水位行分叉："
            f"徽标[{房间键}/{水位值}] vs 水位行[{水位行['房间键']}/{水位行['事件时水位']}]"
        )

    最新 = 取最新徽标(conn, 房间键)
    if 最新 is None:
        最新 = 确保房徽标行(conn, 房间键, 水位值)
    # 幂等：同房同水位且已是本房范围，不重复推进世代
    if (
        最新["范围"] == 本房范围
        and 最新["房间键"] == 房间键
        and 最新["水位值"] == 水位值
    ):
        return 最新

    新世代 = int(最新["徽标世代"]) + 1
    conn.execute(
        """INSERT INTO 扫描范围徽标(房间键, 范围, 水位值, 徽标世代, 时刻)
           VALUES (?,?,?,?,?)""",
        (房间键, 本房范围, 水位值, 新世代, 此刻()),
    )
    行 = 取最新徽标(conn, 房间键)
    # 写后四要素自核：任一不符即抛错，调用方整票回滚
    if (
        行 is None
        or 行["范围"] != 本房范围
        or 行["房间键"] != 房间键
        or 行["水位值"] != 水位值
        or int(行["徽标世代"]) != 新世代
    ):
        raise RuntimeError(f"徽标写后自核失败，拒绝半截态：{房间键} 世代{新世代}")
    return 行


