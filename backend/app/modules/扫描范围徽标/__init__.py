def 扫描范围(conn, 房间键: str) -> str:
    """关窗扫描唯一采信的范围来源：只认本房最新徽标。

    fail-closed：徽标缺失、范围非本房、房键与本房水位行分叉、水位值与水位行不一致时
    直接抛错——扫描器不得回退到全局，也不得拿陈旧/空徽标关窗。
    """
    if not 房间键:
        raise RuntimeError("扫描范围拒绝：房键为空，禁止无房键全局扫描")
    徽 = 取最新徽标(conn, 房间键)
    if 徽 is None:
        raise RuntimeError(f"扫描范围拒绝：本房徽标缺失（空徽标不得扫描）：{房间键}")
    if 徽["房间键"] != 房间键:
        raise RuntimeError(
            f"扫描范围拒绝：徽标房键[{徽['房间键']}] 与请求房[{房间键}] 分叉"
        )
    if 徽["范围"] != 本房范围:
        raise RuntimeError(
            f"扫描范围拒绝：徽标声明范围[{徽['范围']}] 非本房，本系统禁止出房扫描：房{房间键}"
        )
    水位行 = conn.execute(
        "SELECT 事件时水位 FROM 水位线 WHERE 房间键=?", (房间键,)
    ).fetchone()
    if 水位行 is None or 水位行["事件时水位"] != 徽["水位值"]:
        raise RuntimeError(
            f"扫描范围拒绝：徽标水位值与本房水位行分叉（徽标陈旧）：房{房间键}"
        )
    return 本房范围


def 登记全局工单(conn, 工单号: str, 房间键: str = "") -> dict:
    """对照口径「全局切换工单扩权」的唯一落点：只登记审计，永不扩权。

    本系统取舍为事件房键钉本房徽标，任何齐套工单都不允许把徽标改成全局；
    登记动作本身留痕，供核证接口证明「工单存在但扫描仍不出房」。
    """
    if not 工单号:
        raise RuntimeError("工单登记拒绝：工单号为空")
    conn.execute(
        """INSERT OR IGNORE INTO 全局切换工单(工单号, 房间键, 状态, 时刻, 处置)
           VALUES (?,?,?,?,?)""",
        (
            工单号,
            房间键,
            "登记",
            此刻(),
            "本系统采用事件房键钉本房徽标：工单仅审计，不授予全局扫描权，徽标不得改全局",
        ),
    )
    return dict(
        conn.execute(
            "SELECT * FROM 全局切换工单 WHERE 工单号=?", (工单号,)
        ).fetchone()
    )


def _核证一房(conn, 房间键: str) -> dict:
    徽 = 取最新徽标(conn, 房间键)
    水位行 = conn.execute(
        "SELECT 事件时水位, 允许迟到秒, 更新处理时 FROM 水位线 WHERE 房间键=?",
        (房间键,),
    ).fetchone()
    项: dict = {
        "房间键": 房间键,
        "设计取舍": 采用取舍,
        "工单可扩权": 工单扩权,
        "采信徽标": False,
    }
    if 徽 is None:
        项.update({
            "范围": None, "徽标世代": None, "徽标水位值": None, "徽标时刻": None,
            "valid": False, "无效原因": "徽标缺失（空徽标不得扫描）",
        })
    else:
        房键符 = 徽["房间键"] == 房间键
        范围本房 = 徽["范围"] == 本房范围
        水位符 = 水位行 is not None and 水位行["事件时水位"] == 徽["水位值"]
        可解析 = True
        try:
            时间.解析(徽["水位值"])
        except (ValueError, TypeError):
            可解析 = False
        原因 = []
        if not 房键符:
            原因.append("徽标房键与水位行房键分叉")
        if not 范围本房:
            原因.append(f"徽标范围非本房（{徽['范围']}），禁止出房扫描")
        if not 水位符:
            原因.append("徽标水位值与水位行不一致（徽标陈旧）")
        if not 可解析:
            原因.append("徽标水位值不可解析")
        项.update({
            "范围": 徽["范围"],
            "徽标世代": int(徽["徽标世代"]),
            "徽标水位值": 徽["水位值"],
            "徽标时刻": 徽["时刻"],
            "水位行水位": 水位行["事件时水位"] if 水位行 else None,
            "valid": bool(房键符 and 范围本房 and 水位符 and 可解析),
            **({"无效原因": "；".join(原因)} if 原因 else {}),
            "采信徽标": bool(房键符 and 范围本房 and 水位符 and 可解析),
        })
    return 项


def 查徽标(conn, 房间键: str | None = None) -> dict:
    """扫描范围徽标核证只读接口（纯 SELECT，绝不写库）。

    返回：设计取舍、每房最新徽标四要素核证（范围/房键/水位值/世代）、徽标历史、
    全局切换工单审计行。前端「扫描徽标核证」页与测试统一采信此口径。
    """
    if 房间键:
        历史 = [
            dict(r)
            for r in conn.execute(
                "SELECT * FROM 扫描范围徽标 WHERE 房间键=? ORDER BY 徽标世代 DESC, 编号 DESC",
                (房间键,),
            )
        ]
        房列表 = [房间键]
    else:
        历史 = [
            dict(r)
            for r in conn.execute(
                "SELECT * FROM 扫描范围徽标 ORDER BY 编号 DESC LIMIT 50"
            )
        ]
        房列表 = [
            r["房间键"]
            for r in conn.execute(
                "SELECT DISTINCT 房间键 FROM 直播间 ORDER BY 房间键"
            )
        ]
    核证 = [_核证一房(conn, k) for k in 房列表]
    工单 = [
        dict(r)
        for r in conn.execute(
            "SELECT * FROM 全局切换工单 ORDER BY 时刻 DESC, 工单号 DESC LIMIT 20"
        )
    ]
    return {
        "设计取舍": 采用取舍,
        "对照取舍": "全局切换工单扩权（未采用：工单仅登记审计、永不扩权）",
        "工单可扩权": 工单扩权,
        "范围": 本房范围,
        "核证": 核证,
        "徽标": 历史,
        "全局切换工单": 工单,
        "采信徽标": all(r["采信徽标"] for r in 核证) if 核证 else False,
    }
