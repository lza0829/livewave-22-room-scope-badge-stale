"""关窗并发半截（已实现）。

多房并发入流时，关窗扫描必须满足：
- 扫描按房键锁定范围（只扫本房开启窗），不允许一条扫描跨房；
- 单条 UPDATE 原子改状态，逐窗提交于同一事务，不存在「关了 A 房一半、扫到 B 房」的半截态；
- 关窗判定只认本房水位行，调用方须先过 modules.多房串扰隔离.同房校验。

热度窗.尝试关窗 为本模块的落地实现；这里给出房键绑定断言与扫描口径说明。
"""
from __future__ import annotations

状态 = "已实现"


def 断言扫描口径(事件房间键: str, 扫描房间键: str) -> None:
    if 事件房间键 != 扫描房间键:
        raise RuntimeError(
            f"关窗扫描跨房拒绝：事件房[{事件房间键}] vs 扫描房[{扫描房间键}]"
        )


def 本房开启窗sql() -> str:
    """关窗扫描 SQL 骨架：房键条件前置，杜绝跨房扫窗。"""
    return "SELECT 窗键 FROM 热度窗 WHERE 房间键=:房间键 AND 状态='开启'"
